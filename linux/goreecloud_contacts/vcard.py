"""Strictly limited vCard 3.0 import; rejects unsupported data rather than losing it.

Only the profile generated by core.make_vcards is accepted (FN, N, TEL, EMAIL,
ORG). No photos, groups, multi-valued attributes, labels, notes, type parameters,
or arbitrary extensions. All imports remain explicit, local and no-overwrite.
"""
from __future__ import annotations

import os
from pathlib import Path
import stat
from uuid import uuid4

from .core import (
    ContactError, MAX_BUNDLE_BYTES, MAX_CONTACTS,
    validate, validate_collection,
)

PROPERTIES = frozenset(("VERSION", "N", "FN", "TEL", "EMAIL", "ORG"))


def decode_value(value: str) -> str:
    output = []
    i = 0
    while i < len(value):
        char = value[i]
        if char == "\\":
            i += 1
            if i >= len(value) or value[i] not in ("\\", ";", ","):
                raise ContactError("Unsupported vCard escape sequence")
            output.append(value[i])
        elif char in (";", ","):
            raise ContactError("Unescaped vCard punctuation")
        else:
            output.append(char)
        i += 1
    return "".join(output)


def encode_value(value: str) -> str:
    return value.replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,")


def unfold(text: str) -> list[str]:
    if "\r" in text.replace("\r\n", ""):
        raise ContactError("Unsupported vCard line endings")
    physical = text.replace("\r\n", "\n").split("\n")
    if physical and physical[-1] == "":
        physical.pop()
    logical: list[str] = []
    for line in physical:
        try:
            length = len(line.encode("utf-8", errors="strict"))
        except UnicodeError as error:
            raise ContactError("Invalid Unicode in vCard") from error
        if not line or length > 1000:
            raise ContactError("Invalid or oversized vCard line")
        if line[0] in (" ", "\t"):
            if not logical:
                raise ContactError("Invalid folded vCard line")
            combined = logical[-1] + line[1:]
            if len(combined.encode("utf-8")) > 2000:
                raise ContactError("Oversized unfolded vCard field")
            logical[-1] = combined
        else:
            logical.append(line)
    return logical


def parse_vcards(text: str, id_factory=None) -> list[dict]:
    if not isinstance(text, str) or not text:
        raise ContactError("Invalid or oversized vCard file")
    try:
        if len(text.encode("utf-8", errors="strict")) > MAX_BUNDLE_BYTES:
            raise ContactError("Invalid or oversized vCard file")
    except UnicodeError as error:
        raise ContactError("Invalid vCard Unicode") from error
    if id_factory is None:
        id_factory = lambda: str(uuid4())
    if text.startswith("\ufeff"):
        text = text[1:]
    current: dict[str, str] | None = None
    contacts = []
    for line in unfold(text):
        if line == "BEGIN:VCARD":
            if current is not None:
                raise ContactError("Nested vCard not supported")
            current = {}
            continue
        if current is None:
            raise ContactError("vCard content outside a record")
        if line == "END:VCARD":
            if current.get("VERSION") != "3.0" or "FN" not in current or "N" not in current:
                raise ContactError("Missing or unsupported vCard identity")
            name = decode_value(current["FN"])
            if current["N"] != encode_value(name) + ";;;;":
                raise ContactError("Structured name cannot be imported without data loss")
            contacts.append(validate({
                "id": id_factory(), "name": name,
                "phone": decode_value(current.get("TEL", "")),
                "email": decode_value(current.get("EMAIL", "")),
                "organization": decode_value(current.get("ORG", "")),
                "favorite": False,
            }))
            if len(contacts) > MAX_CONTACTS:
                raise ContactError("Too many vCards")
            current = None
            continue
        index = line.find(":")
        if index <= 0:
            raise ContactError("Invalid vCard property")
        name = line[:index]
        if name not in PROPERTIES or name in current:
            raise ContactError("Unsupported or duplicate vCard property")
        current[name] = line[index + 1:]
    if current is not None or not contacts:
        raise ContactError("Incomplete or empty vCard file")
    return validate_collection(contacts)


def visible_identity(raw: dict) -> tuple[str, str, str, str]:
    item = validate(raw)
    return (item["name"].casefold(), item["phone"],
            item["email"].casefold(), item["organization"].casefold())


def read_vcards_file(path: Path | str) -> list[dict]:
    flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0)
    try:
        fd = os.open(path, flags)
        with os.fdopen(fd, "rb") as file:
            meta = os.fstat(file.fileno())
            if not stat.S_ISREG(meta.st_mode) or meta.st_size > MAX_BUNDLE_BYTES:
                raise ContactError("Invalid vCard file size or type")
            contents = file.read(MAX_BUNDLE_BYTES + 1)
        return parse_vcards(contents.decode("utf-8", errors="strict"))
    except (OSError, UnicodeError) as error:
        raise ContactError("Cannot safely read vCard file") from error
